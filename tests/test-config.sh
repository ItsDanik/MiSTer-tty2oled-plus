INIT="${INSTALL}/S60tty2oled"; PREVIEW_TOOL="${INSTALL}/tty2oledplus_preview.sh"
UI_BIN_SRC="${BIN}"; UI_FBDEV="${FB}"; UI_BIN_COPY="${TMP}/config.copy"
SLEEPFILE="${TMP}/sleep"; DAEMONLOG="${TMP}/daemon.log"
