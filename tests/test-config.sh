#!/bin/bash
#
# Tests for the settings utility that draws on the framebuffer:
# tools/settings-ui/config.c (tty2oledplus_config), the table and the changes
# tty2oledplus_settings.sh passes it and takes back, and
# tty2oledplus_preview.sh, which shows a setting on the display while it is
# changed.
#
# The utility is built for this machine and run against a file standing in
# for /dev/fb0, with its keys on a pipe - the bytes a terminal sends for the
# arrows, Enter and Escape, which is how a pad arrives on a MiSTer too. What
# is checked is what it hands back and what it told the preview; the pixels
# only for what a picture cannot be argued with about: that something is
# drawn, in cyan and nothing else, inside what a 15kHz CRT shows.
#
# The preview is run against a pipe standing in for the display's port, and
# what reaches it compared with what the daemon would send.
#
#   ./tests/test-config.sh

set -u

HERE="$(cd "$(dirname "${0}")" && pwd)"
ROOT="$(dirname "${HERE}")"
TMP="${HERE}/fixtures/tmp/config"
rm -rf "${TMP}"; mkdir -p "${TMP}/install"

INSTALL="${TMP}/install"

PASS=0; FAIL=0
ok() {
  local label="${1}" got="${2}" want="${3}"
  if [ "${got}" = "${want}" ]; then
    PASS=$((PASS+1)); printf '  \033[32mok\033[0m   %s\n' "${label}"
  else
    FAIL=$((FAIL+1))
    printf '  \033[31mFAIL\033[0m %s\n       want: [%s]\n       got:  [%s]\n' "${label}" "${want}" "${got}"
  fi
}
section() { printf '\n\033[1m%s\033[0m\n' "${1}"; }

if ! command -v gcc >/dev/null 2>&1; then
  printf '\033[33mgcc not found - skipping the settings utility tests\033[0m\n'
  exit 0
fi

# ---------------------------------------------------------------------------
section "building it"
# ---------------------------------------------------------------------------
"${ROOT}/tools/build-config.sh" --host > "${TMP}/build.out" 2>&1; RC="${?}"
ok "builds clean under -Wall -Wextra -Werror, with ASan and UBSan" "${RC}" "0"
[ "${RC}" -eq 0 ] || { cat "${TMP}/build.out"; printf '\n\033[1mResults:\033[0m %d passed, %d failed\n' "${PASS}" "$((FAIL))"; exit 1; }
BIN="${ROOT}/tools/settings-ui/build/host/tty2oledplus_config"

ok "the fonts are the ones genfont.sh makes: four, generated" \
   "$(grep -c '^static const Font font_' "${ROOT}/tools/settings-ui/fonts.h"):$(grep -c 'Generated by tools/settings-ui/genfont.sh' "${ROOT}/tools/settings-ui/fonts.h")" "4:1"

# The real install's inis, so the table is the real one.
cp "${ROOT}/tty2oled-system.ini" "${INSTALL}/"
printf '# mine\nCONTRAST="180"\nTRANSITION="31"\n' > "${INSTALL}/tty2oled-user.ini"

# The editor as a library, for its table.
# shellcheck source=../tools/tty2oledplus_settings.sh
T2OP_SETTINGS_LIB=yes T2OP_INSTALL="${INSTALL}" T2OP_UI_LIB="${ROOT}/tools/tty2oledplus_ui.sh" \
  . "${ROOT}/tools/tty2oledplus_settings.sh"

TABLE="${TMP}/table.tsv"
dump_table > "${TABLE}"

# ---------------------------------------------------------------------------
section "the table the script hands over"
# ---------------------------------------------------------------------------
NSET=0; BAD=""
for c in ${CATEGORIES}; do
  while IFS='|' read -r k _; do
    NSET=$((NSET + 1))
    want="$(current_value "${k}")"
    got="$(awk -F'\t' -v k="${k}" '$1 == "V" && $2 == k { print $3 }' "${TABLE}")"
    [ "${want}" = "${got}" ] || BAD="${BAD} ${k}"
    want="$(default_value "${k}")"
    got="$(awk -F'\t' -v k="${k}" '$1 == "D" && $2 == k { print $3 }' "${TABLE}")"
    [ "${want}" = "${got}" ] || BAD="${BAD} ${k}:default"
  done < <(settings_in "${c}")
done
ok "every setting the menus offer is in it" "$(grep -c '^S' "${TABLE}")" "${NSET}"
ok "with the value and the default ini_get finds, though read in one pass" "${BAD}" ""
ok "a section a line, each with its line of help" \
   "$(awk -F'\t' '$1 == "C" && $3 != "" && $4 != ""' "${TABLE}" | wc -l | tr -d ' ')" "$(printf '%s\n' ${CATEGORIES} | wc -l | tr -d ' ')"
ok "an enum's spec is its pairs, not the variable's name" \
   "$(awk -F'\t' '$1 == "S" && $2 == "TRANSITION" { print ($4 ~ /^-2=Fade/) }' "${TABLE}")" "1"
ok "the pinned fields are chosen from the shown ones" \
   "$(awk -F'\t' '$1 == "S" && $2 == "METADATA_PINNED" { print $4 }' "${TABLE}")" "@METADATA_FIELDS"
# A caption for a key that is not a setting would be a divider that never
# appears, and nobody would be told.
LOST=""
while IFS='=' read -r k _; do
  grep -q "^S	${k}	" "${TABLE}" || LOST="${LOST} ${k}"
done <<< "${SUBSECTIONS}"
ok "every sub-section starts at a setting that is offered" "${LOST}" ""
ok "and each is a divider in the table, right above that setting" \
   "$(grep -c '^G' "${TABLE}"):$(grep -A1 '^G	Super Attract Mode$' "${TABLE}" | tail -n1 | cut -f1,2)" \
   "$(printf '%s\n' "${SUBSECTIONS}" | grep -c .):S	SAM_HEADER"
ok "nothing is pending in a fresh one" "$(grep -c '^P' "${TABLE}")" "0"
PENDING[CONTRAST]="77"
ok "what is changed and not saved goes along" "$(dump_table | grep -c "^P	CONTRAST	77$")" "1"
PENDING=()

printf 'A="1"\nB=two # note\nC='"'"'three'"'"'\n  D="four" # x\n#E="5"\nA="6"\n' > "${TMP}/odd.ini"
ok "ini_dump reads what ini_get reads: quotes, comments, the last one wins" \
   "$(ini_dump "${TMP}/odd.ini" | LC_ALL=C sort | tr '\t\n' '= ')" "A=6 B=two C=three D=four "

# ---------------------------------------------------------------------------
# Driving it. Keys are what a terminal sends.
# ---------------------------------------------------------------------------
U=$'\033[A'; D=$'\033[B'; L=$'\033[D'; R=$'\033[C'; OK=$'\r'; ESC=$'\033'; END=$'\033[F'
OUT="${TMP}/out.txt"; FB="${TMP}/fb.raw"; PV="${TMP}/preview.txt"

run() {  # run <keys> [more options] - the exit code in RC
  local keys="${1}"; shift
  rm -f "${OUT}" "${PV}"
  printf '%s' "${keys}" | "${BIN}" --table "${TABLE}" --out "${OUT}" --fb "${FB}" \
    --geometry 320x240x32 --preview "cat > '${PV}'" "$@" 2> "${TMP}/stderr"
  RC="${?}"
}
out() { tr '\n' '|' < "${OUT}"; }
# The sections, in order: display console arcade dvd panel transition updates advanced.
PANEL="${D}${D}${D}${D}${OK}"            # Brightness and burn-in; CONTRAST is first
TRANS="${D}${D}${D}${D}${D}${OK}"        # Changing picture; TRANSITION is first
DISPLAY_SEC="${OK}"                      # What the display shows; SHOW_METADATA is first
CONSOLE="${D}${OK}"                      # METADATA_FIELDS, METADATA_PINNED, SHOW_DESCRIPTION
ARCADE="${D}${D}${OK}"                   # ARCADE_FIELDS, ARCADE_FIELDS_WIDE, ARCADE_PINNED

# ---------------------------------------------------------------------------
section "leaving"
# ---------------------------------------------------------------------------
run ""
ok "the keys running out is its own exit code" "${RC}" "13"
ok "and sanitizers found nothing" "$(grep -c 'ERROR\|runtime error' "${TMP}/stderr")" "0"
run "${ESC}"
ok "Cancel with nothing changed leaves" "${RC}:$(out)" "10:"
run "${PANEL}${R}${ESC}${ESC}${OK}"
ok "Cancel with a change asks, and Save is the default" "${RC}:$(out)" "0:CONTRAST=181|"
run "${PANEL}${R}${ESC}${ESC}${R}${OK}"
ok "Discard leaves with nothing to save" "${RC}:$(out)" "10:"
run "${PANEL}${R}${ESC}${ESC}${R}${R}${OK}"
ok "Stay goes back to the settings" "${RC}:$(out)" "13:CONTRAST=181|"
run "${PANEL}${R}${ESC}${ESC}${ESC}"
ok "and so does Cancel on the question" "${RC}" "13"
run "${PANEL}${R}${ESC}${END}${OK}"
ok "Save and exit is the last row of the main screen" "${RC}:$(out)" "0:CONTRAST=181|"
run "${U}${OK}"
ok "which is Exit when nothing changed" "${RC}:$(out)" "10:"

# ---------------------------------------------------------------------------
section "a switch, a slider, a selector"
# ---------------------------------------------------------------------------
run "${DISPLAY_SEC}${L}"
ok "Left switches off" "$(out)" "SHOW_METADATA=no|"
run "${DISPLAY_SEC}${L}${R}"
ok "Right switches on again, and nothing is changed after all" "$(out)" ""
run "${DISPLAY_SEC}${OK}"
ok "OK flips a switch" "$(out)" "SHOW_METADATA=no|"

run "${PANEL}${L}${L}${L}"
ok "Left moves a slider down a step at a time" "$(out)" "CONTRAST=177|"
run "${PANEL}${R}${R}${R}${R}${R}${R}${R}${R}${R}${R}${R}${R}"
# Eight single steps, then fives - on the fives' grid: 188, 190, 195, 200, 205.
ok "a held direction speeds up" "$(out)" "CONTRAST=205|"
HOLD=""; for _ in $(seq 60); do HOLD="${HOLD}${R}"; done
run "${PANEL}${HOLD}"
ok "and stops at the top" "$(out)" "CONTRAST=255|"
run "${PANEL}${D}${R}"
ok "a slider with a step moves by it" "$(out)" "CONTRAST_FADE_MS=850|"
printf 'CONTRAST_FADE_MS="820"\n' >> "${INSTALL}/tty2oled-user.ini"; dump_table > "${TABLE}"
run "${PANEL}${D}${R}"
ok "and onto its grid from a value that is off it" "$(out)" "CONTRAST_FADE_MS=850|"
run "${PANEL}${D}${L}"
ok "either way" "$(out)" "CONTRAST_FADE_MS=800|"
sed -i '/CONTRAST_FADE_MS/d' "${INSTALL}/tty2oled-user.ini"; dump_table > "${TABLE}"

run "${TRANS}${R}"
ok "Right moves a selector to the next choice" "$(out)" "TRANSITION=32|"
run "${TRANS}${L}${L}"
ok "Left to the one before" "$(out)" "TRANSITION=23|"

# Dividers take rows on screen and none of the highlight's stops: the fifth
# Down in the first section is the sixth setting, whatever is drawn between.
run "${DISPLAY_SEC}${D}${D}${D}${D}${D}"
ok "the highlight steps over a sub-section's divider" "$(tail -n1 "${PV}")" "focus SAM_TIMER"
run "${DISPLAY_SEC}${U}${OK}"
ok "and Up from the first setting wraps to the last" "$(tail -n1 "${PV}"):$(out)" "focus VSCROLL_SPEED:"

# ---------------------------------------------------------------------------
section "the popups: a list, a number, a keyboard"
# ---------------------------------------------------------------------------
run "${TRANS}${OK}${D}${D}${OK}"
ok "OK on a selector opens the list, on the choice in force" "$(out)" "TRANSITION=33|"
run "${TRANS}${OK}${D}${D}${ESC}"
ok "Cancel in the list puts the old one back" "$(out)" ""
ok "and the display is told it is back" "$(grep '^set TRANSITION' "${PV}" | tail -n1)" "set TRANSITION 31"

run "${PANEL}${OK}${U}${U}${OK}"
ok "the number editor: Up adds one to the digit" "$(out)" "CONTRAST=182|"
run "${PANEL}${OK}${L}${D}${D}${D}${OK}"
ok "Left moves to the tens" "$(out)" "CONTRAST=150|"
run "${PANEL}${OK}${L}${L}${U}${OK}"
ok "past the top stops at the top" "$(out)" "CONTRAST=255|"
run "${PANEL}${OK}${D}${D}${ESC}"
ok "Cancel undoes it" "$(out)" ""
run "${PANEL}${OK}${L}${L}${D}${D}42${OK}"
ok "a keyboard's digits go in at the right" "$(out)" "CONTRAST=42|"
run "${PANEL}${D}${D}${D}${D}${D}${OK}${U}${U}${U}${U}${U}-${OK}"
ok "a minus that would go below the least stops at it" "$(out)" ""
run "${PANEL}${D}${D}${D}${D}${D}${OK}${U}${U}${U}${OK}"
ok "(and Up from -1 counts up)" "$(out)" "DIM_WAKE=2|"

SAM="${DISPLAY_SEC}${D}${D}${D}${D}"     # SAM_HEADER_TEXT
# The fifth row is the actions: Aa, Space, Delete, Clear, Done.
run "${SAM}${OK}${D}${D}${D}${D}${R}${R}${R}${OK}"
ok "the keyboard: Clear empties the field" "$(out)" "SAM_HEADER_TEXT=|"
run "${SAM}${OK}${D}${D}${D}${D}${R}${R}${R}${OK}${U}${U}${U}${U}${OK}${R}${OK}${ESC}"
ok "Cancel undoes all of it" "$(out)" ""
run "${SAM}${OK}"$'\t'"${L}${L}${OK}${U}${U}${U}${R}${OK}${D}${D}${D}"$'\t'"${OK}${ESC}${ESC}${OK}"
ok "Delete takes the last character, a key adds one, Done keeps it" "$(out)" "SAM_HEADER_TEXT=Super Attract Modu|"
run "${SAM}${OK}"$'\177\177\177\177'"Demo!${OK}${ESC}${ESC}${OK}"
ok "a real keyboard types straight in, and its Enter is Done" "$(out)" "SAM_HEADER_TEXT=Super Attract Demo!|"
run "${SAM}${OK}"$'\177\177\177\177\177\177\177\177\177\177\177\177\177\177\177\177\177\177\177\177'"a\"b\$c\`d'e\\f${OK}${ESC}${ESC}${OK}"
ok "what an ini value cannot hold is not typed" "$(out)" "SAM_HEADER_TEXT=abcdef|"
LONG=""; for _ in $(seq 40); do LONG="${LONG}x"; done
run "${SAM}${OK}${LONG}${OK}${ESC}${ESC}${OK}"
ok "nor more than the setting's length" "$(awk -F= '{ print length($2) }' "${OUT}")" "24"

# ---------------------------------------------------------------------------
section "lists: ticking, order, and what depends on them"
# ---------------------------------------------------------------------------
FIELDS="$(current_value METADATA_FIELDS)"; PINNED="$(current_value METADATA_PINNED)"
FIRST="${FIELDS%% *}"; REST="${FIELDS#* }"; SECOND="${REST%% *}"
run "${CONSOLE}${OK}${R}${ESC}${ESC}${ESC}${OK}"
ok "Right moves a ticked field later" "$(grep -c "^METADATA_FIELDS=${SECOND} ${FIRST} " "${OUT}")" "1"
run "${CONSOLE}${OK}${R}${L}${ESC}${ESC}${ESC}"
ok "and Left back again" "$(out)" ""
run "${CONSOLE}${OK}${OK}${ESC}${ESC}${ESC}${OK}"
ok "OK unticks: the field leaves the list" "$(grep -c "^METADATA_FIELDS=${REST}$" "${OUT}")" "1"
ok "and the pinned list with it, when it was pinned there" \
   "$(grep '^METADATA_PINNED=' "${OUT}")" \
   "$(case " ${PINNED} " in *" ${FIRST} "*) printf 'METADATA_PINNED=%s' "$(list_intersect "${PINNED}" "${REST}")" ;; esac)"
run "${CONSOLE}${OK}${OK}${ESC}${D}${OK}"
ok "the pinned checklist offers only what is shown" "$(grep -c "focus METADATA_PINNED" "${PV}")" "1"
# Unticked goes to the end of the unticked; ticking it again appends it.
NF="$(printf '%s' "${FIELDS}" | wc -w)"
DOWN=""; for _ in $(seq $((NF - 1))); do DOWN="${DOWN}${D}"; done
run "${CONSOLE}${OK}${OK}${DOWN}${OK}${ESC}${ESC}${ESC}${OK}"
ok "ticked again it goes on the end, the rest in their order" \
   "$(grep -c "^METADATA_FIELDS=${REST} ${FIRST}$" "${OUT}")" "1"

AF="$(current_value ARCADE_FIELDS)"
run "${ARCADE}${D}${D}${L}${ESC}${ESC}${OK}"
ok "a leading run gets shorter from the end" \
   "$(grep '^ARCADE_PINNED=' "${OUT}")" "ARCADE_PINNED=$(list_prefix "${AF}" $(( $(printf '%s' "$(current_value ARCADE_PINNED)" | wc -w) - 1 )))"
run "${ARCADE}${D}${D}${R}${R}${R}${R}${R}${ESC}${ESC}${OK}"
ok "and is three fields at most" "$(grep '^ARCADE_PINNED=' "${OUT}")" "ARCADE_PINNED=$(list_prefix "${AF}" 3)"
run "${ARCADE}${OK}${R}${ESC}${ESC}${ESC}${OK}"
ok "reordering the list it runs along reorders it too" \
   "$(grep '^ARCADE_PINNED=' "${OUT}")" "ARCADE_PINNED=$(list_prefix "$(grep '^ARCADE_FIELDS=' "${OUT}" | cut -d= -f2)" "$(printf '%s' "$(current_value ARCADE_PINNED)" | wc -w)")"

# ---------------------------------------------------------------------------
section "back to the defaults"
# ---------------------------------------------------------------------------
run "${U}${U}${OK}${OK}"
ok "the answer already highlighted is No" "$(out)" ""
run "${U}${U}${OK}${R}${OK}${D}${OK}"
ok "Yes puts back what differs from the release, to be saved" "${RC}:$(LC_ALL=C sort "${OUT}" | tr '\n' '|')" "0:CONTRAST=$(default_value CONTRAST)|TRANSITION=$(default_value TRANSITION)|"

# ---------------------------------------------------------------------------
section "what the preview is told"
# ---------------------------------------------------------------------------
run "${PANEL}${R}${R}${R}${D}"
ok "the highlighted setting, and where a value ended up - not every step" \
   "$(tr '\n' '|' < "${PV}")" "focus -|set CONTRAST 183|focus CONTRAST_FADE_MS|"
run "${PANEL}${R}${ESC}${ESC}${R}${OK}"
ok "a change discarded is taken back on the display" "$(tail -n1 "${PV}")" "set CONTRAST 180"
PENDING[CONTRAST]="99"; dump_table > "${TABLE}"; PENDING=()
run ""
ok "changes from before this run, not saved, are told again" "$(grep -c '^set CONTRAST 99$' "${PV}")" "1"
ok "and still handed back" "$(out)" "CONTRAST=99|"
dump_table > "${TABLE}"
run "${PANEL}${R}" --preview "exit 3"
ok "a preview that dies takes nothing with it" "${RC}:$(out)" "13:CONTRAST=181|"

# ---------------------------------------------------------------------------
section "the picture"
# ---------------------------------------------------------------------------
# 320x240, 32 bits, blue-green-red-x: red must be nothing anywhere.
pixels() {  # pixels <file> <bytes a pixel> - "lit red" counts
  python3 - "$1" "$2" <<'EOF'
import sys
d = open(sys.argv[1], 'rb').read(); n = int(sys.argv[2])
lit = red = 0
for i in range(0, len(d), n):
    if n == 4:
        b, g, r = d[i], d[i + 1], d[i + 2]
    else:
        v = d[i] | d[i + 1] << 8
        r, g, b = v >> 11, (v >> 5) & 63, v & 31
    if g or b: lit += 1
    if r: red += 1
    if (g >> (0 if n == 4 else 1)) != b: red += 1      # green and blue together: cyan
print(lit > 1000, red)
EOF
}
run "" --dump "${TMP}/main.pgm"
ok "something is drawn, and all of it cyan" "$(pixels "${FB}" 4)" "True 0"
ok "sixteen levels and no more" \
   "$(python3 -c "
import sys
d = open(sys.argv[1], 'rb').read()
d = d[len(d) - 320 * 240:]
print(all(v % 17 == 0 for v in d), len(set(d)) > 4)" "${TMP}/main.pgm")" "True True"
# Every screen, and every popup over one: nothing lit in the margin a 15kHz
# CRT hides - 16 pixels at the sides, 12 above and below.
MARGIN=""
for keys in "" "${PANEL}" "${DISPLAY_SEC}${D}${D}${D}${D}${D}${D}${D}${D}${D}${D}${D}" "${TRANS}${OK}" "${PANEL}${OK}" "${SAM}${OK}" "${CONSOLE}${OK}" "${PANEL}${R}${ESC}${ESC}" "${DISPLAY_SEC}${U}"; do
  run "${keys}" --dump "${TMP}/shot.pgm"
  MARGIN="${MARGIN}$(python3 -c "
import sys
d = open(sys.argv[1], 'rb').read()
d = d[len(d) - 320 * 240:]
bad = sum(1 for y in range(240) for x in range(320)
          if d[y * 320 + x] and (x < 16 or x >= 304 or y < 12 or y >= 228))
print(bad)" "${TMP}/shot.pgm") "
done
ok "nothing is drawn where a CRT's overscan would hide it" "${MARGIN}" "0 0 0 0 0 0 0 0 0 "

rm -f "${FB}"
printf '' | "${BIN}" --table "${TABLE}" --out "${OUT}" --fb "${FB}" --geometry 320x240x16 2>/dev/null
ok "a 16-bit framebuffer gets the same, in its own format" "$(wc -c < "${FB}" | tr -d ' '):$(pixels "${FB}" 2)" "153600:True 0"
rm -f "${FB}"
printf '' | "${BIN}" --table "${TABLE}" --out "${OUT}" --fb "${FB}" --geometry 720x480x32 2>/dev/null
ok "a bigger one gets it doubled and centred" \
   "$(python3 -c "
import sys
d = open(sys.argv[1], 'rb').read()
def lit(x, y): return d[(y * 720 + x) * 4 + 1] != 0
cols = [x for x in range(720) if any(lit(x, y) for y in range(480))]
rows = [y for y in range(480) if any(lit(x, y) for x in range(720))]
print(min(cols) >= 40 + 32, max(cols) < 40 + 608, min(rows) >= 24, max(rows) < 456,
      all(lit(x, y) == lit(x + 1, y) == lit(x, y + 1) for y in rows[::2][:40] for x in range(40, 680, 2)))" "${FB}")" \
   "True True True True True"
printf '' | "${BIN}" --table "${TABLE}" --out "${OUT}" --fb "${FB}" --geometry 256x192x32 2>/dev/null; RC="${?}"
ok "one too small to hold it is refused, for the menus to take over" "${RC}" "12"
printf '' | "${BIN}" --table "${TMP}/no-such-table" --out "${OUT}" --fb "${FB}" --geometry 320x240x32 2>/dev/null; RC="${?}"
ok "and so is no table" "${RC}" "12"

