preview() {  # preview <lines...> - what reached the port, a command a line, in WIRE
  local line
  rm -f "${TMP}/tty.fifo"; mkfifo "${TMP}/tty.fifo"
  exec 9<>"${TMP}/tty.fifo"
  cat <&9 > "${TMP}/tty.log" & local reader=$!
  # "~" is a pause: lines that arrive together are taken together.
  for line in "$@"; do if [ "${line}" = "~" ]; then sleep 0.3; else printf '%s\n' "${line}"; fi; done \
    | T2OP_PREVIEW_TTY="${TMP}/tty.fifo" T2OP_PREVIEW_TICK=0.05 T2OP_PREVIEW_FW="${VERSION}" \
    LC_ALL=C bash "${PI}/tty2oledplus_preview.sh" --install "${PI}" > /dev/null 2>&1
  sleep 0.2; kill "${reader}" 2>/dev/null; wait "${reader}" 2>/dev/null
  exec 9>&-
  WIRE="$(LC_ALL=C grep -a -o 'CMD[A-Z]*[ -~]*' "${TMP}/tty.log")"
}
