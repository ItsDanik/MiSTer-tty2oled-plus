   "$(cmp -s "${BIN}" "${UI_BIN_COPY}" && echo same):${T2OP_FB_BIN}" "same:${UI_BIN_COPY}"

ui() {  # ui <keys> - fb_ui with these keys; its exit code in RC
  rm -f "${TMP}/init.log" "${TMP}/script-preview.txt"
  printf '%s' "${1}" > "${TMP}/keys"
  fb_ui < "${TMP}/keys" 2> "${TMP}/stderr"; RC="${?}"
}
user() { grep -v '^#' "${INSTALL}/tty2oled-user.ini" | grep . | LC_ALL=C sort | tr '\n' '|'; }

ui "${PANEL}${R}${ESC}${END}${OK}"
ok "Save writes the user ini" "${RC}:$(user)" '0:CONTRAST="181"|TRANSITION="31"|'
ok "the daemon is stopped for the preview and started after, with what was saved" \
   "$(tr '\n' ' ' < "${TMP}/init.log")" "status stop start "
ok "the preview ran, and heard the change" "$(grep -c '^set CONTRAST 181$' "${TMP}/script-preview.txt")" "1"
ok "the user's own lines are still there" "$(grep -c '^# mine$' "${INSTALL}/tty2oled-user.ini")" "1"

ui "${PANEL}${L}${ESC}${ESC}${R}${OK}"
ok "Discard writes nothing" "${RC}:$(user)" '0:CONTRAST="181"|TRANSITION="31"|'
ok "and the daemon goes back to how it was found" "$(tr '\n' ' ' < "${TMP}/init.log")" "status stop start "
T2OP_TEST_STATUS=1 ui "${ESC}"
